<?php

namespace App\Actions\ApprovalProccessActions;

use App\Models\ApprovalProcess\ApprovalRequestLineModel;
use App\Models\ApprovalProcess\ApprovalRequestModel;
use App\Models\JournalEntryDraft;

class DetermineJournalEntryApprovalStatus
{
    public function __construct(protected ApprovalRequestModel $approvalRequestModel, protected ApprovalRequestLineModel $approvalRequestLineModel)
    {
        $this->approvalRequestModel = $approvalRequestModel;
        $this->approvalRequestLineModel = $approvalRequestLineModel;
    }

    public function handle()
    {
        // -=Without, A=Generated by Authorizer, C=Canceled, N=Rejected, P=Generated, W=Pending, Y=Approved

        $totalApproversRequiredForAction = $this->approvalRequestLineModel->Status == 'Y' ? $this->approvalRequestLineModel->approvalstage->MaxReqr : $this->approvalRequestLineModel->approvalstage->MaxRejReqr;
        $draftDocument = JournalEntryDraft::where('id', $this->approvalRequestModel->DraftEntry)->first();

        $totalActionDone = ApprovalRequestLineModel::where('WddCode', $this->approvalRequestModel->id)
            ->where('StepCode', $this->approvalRequestLineModel->StepCode)
            ->where('SortId', $this->approvalRequestLineModel->SortId)
            ->where('Status', $this->approvalRequestLineModel->Status)
            ->count();

        $pendingStages = ApprovalRequestLineModel::where('WddCode', $this->approvalRequestModel->id)
            ->whereNotIn('StepCode', [$this->approvalRequestLineModel->StepCode])
            ->where('SortId', '>', $this->approvalRequestLineModel->SortId)
            ->orderBy('SortId', 'asc')
            ->get();

        if ($pendingStages->count() <= 0) {

            if ($totalActionDone >= $totalApproversRequiredForAction) {

                $draftDocument->update([
                    'WddStatus' => $this->approvalRequestLineModel->Status,
                    'ProcesStat' => $this->approvalRequestLineModel->Status,
                ]);

                $this->approvalRequestModel->update([
                    'Status' => $this->approvalRequestLineModel->Status,
                    'ProcesStat' => $this->approvalRequestLineModel->Status,
                ]);

      

            }

            return;
        }

        $nextApprovalRequestLine = $pendingStages->first();

        if ($totalActionDone >= $this->approvalRequestLineModel->approvalstage->MaxRejReqr && $this->approvalRequestLineModel->Status == 'N') {
            $this->approvalRequestModel->update([
                'Status' => 'N',
            ]);

            $draftDocument->update([
                'WddStatus' => 'N',
                'ProcesStat' => 'N',
            ]);
        }

        if ($totalActionDone >= $this->approvalRequestLineModel->approvalstage->MaxReqr && $this->approvalRequestLineModel->Status == 'Y') {
            $this->approvalRequestModel->update([
                'CurrStep' => $nextApprovalRequestLine->StepCode,
            ]);

            $draftDocument->update([
                'WddStatus' => 'W',
                'ProcesStat' => 'W',
            ]);
        }

    }
}
